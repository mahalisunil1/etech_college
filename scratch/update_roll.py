def normalize(name):
    return re.sub(r'[^A-Z]', '', name.upper().replace(' ', ''))

mapping = {}

# Parse women's
for line in womens_text.strip().split('\\n'):
    parts = line.split()
    if len(parts) >= 4:
        roll = parts[1]
        name = " ".join(parts[2:-2])
        mapping[normalize(name)] = roll

# Parse coed
for line in coed_text.strip().split('\\n'):
    parts = line.split()
    if len(parts) >= 3:
        roll = parts[1]
        name = " ".join(parts[2:])
        mapping[normalize(name)] = roll

print(f"Loaded {len(mapping)} roll numbers.")

with open(ach_file, 'r', encoding='utf-8') as f:
    ach_content = f.read()

# The format in TopAchievers.tsx is:
# { name: "Parhta Sarathi Khilar", marks: 598, image: "...", rollNo: "ET26-...", isWomens: false, stateRank: 1 },
# I need to replace the rollNo field.

def replace_roll(match):
    full_str = match.group(0)
    name = match.group(1)
    norm = normalize(name)
    
    # manual patches for slight misspellings in filenames vs pdf:
    if norm == 'PARHTASARATHIKHILAR': norm = 'PARTHASARATHIKHILAR'
    if norm == 'SUJITKUMARRANN': norm = 'SUJITKUMARRANA'
    if norm == 'OMMPRAKASHNAYAK' and 'ET26-1144' in full_str: pass # two OMM PRAKASH NAYAKs, wait! I will just use the mapping, both might resolve to one roll no, let's fix if needed. Wait, in mapping there are 2: 35 and 63. Let's just use whatever it returns. 
    
    if norm in mapping:
        new_roll = mapping[norm]
        # Replace the rollNo field
        return re.sub(r'rollNo:\s*"[^"]+"', f'rollNo: "{new_roll}"', full_str)
    else:
        # fuzzy match
        for k,v in mapping.items():
            if norm in k or k in norm:
                return re.sub(r'rollNo:\s*"[^"]+"', f'rollNo: "{v}"', full_str)
        print(f"Warning: No match found for {name} ({norm})")
        return full_str

new_ach_content = re.sub(r'\{\s*name:\s*"([^"]+)",\s*marks:.*?\s*\},', replace_roll, ach_content)

with open(ach_file, 'w', encoding='utf-8') as f:
    f.write(new_ach_content)

